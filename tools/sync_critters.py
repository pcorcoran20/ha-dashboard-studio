"""Copies the theme critters (art, CSS and layer builder) from studio.html into the card bundle,
so Home Assistant shows the same critters as the Studio preview. Run after changing them in the Studio."""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
studio = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'dashboard_studio/rootfs/app/studio.html'
cards = [root / 'dist/dashboard-studio-card.js', root / 'dashboard_studio/rootfs/app/dashboard-studio-card.js']
s = studio.read_text()

lines = s.split('\n')
a = next(i for i, l in enumerate(lines) if l.startswith('.dash[data-fun="duck"]'))
b = next(i for i, l in enumerate(lines) if l.startswith('.dash[data-fun="terminal"] .hd-greet::after'))
css = []
for l in lines[a:b]:
    if l.startswith(('.dash[data-fun', '.dash:is(', '.dash.glitch', '@keyframes glitch')): continue
    css.append(l.replace('.dash.calm ', '.calm ').replace('var(--f-body)', 'system-ui, sans-serif'))
css.append('.calm *{animation:none !important}')

art = re.findall(r'^const (?:DUCK|WHALE|ELEPHANT|TUBE|LEAF|PARROT|CRAB|ROCKET|SEALION|GIFT|PUMPKIN|BAT|MENORAH|DIYA|LANTERN|HEART|BUNNY) = .*?;$', s, re.M | re.S)
body = re.search(r"  let h = '';\n(.*?)\n  \$\('fun'\)\.innerHTML = h;", s, re.S).group(1).replace('eggs.mother', 'false')

block = '\n'.join([
    '/* @critters-start: generated by tools/sync_critters.py from the Studio. Edit there, then run the script. */',
    'const CRIT_CSS = `' + '\n'.join(css).replace('`', '\\`') + '`;',
    *[x.replace('const ', 'const CR_', 1) for x in art],
    'function critterHTML(fun, calm) {',
    '  const r = (a, b) => (a + Math.random() * (b - a)).toFixed(2);',
    "  let h = '';",
    re.sub(r'\b(DUCK|WHALE|ELEPHANT|TUBE|LEAF|PARROT|CRAB|ROCKET|SEALION|GIFT|PUMPKIN|BAT|MENORAH|DIYA|LANTERN|HEART|BUNNY)\b', r'CR_\1', body),
    '  return h;',
    '}',
    '/* @critters-end */',
])
for c in cards:
    t = c.read_text()
    if '/* @critters-start' in t:
        t = re.sub(r'/\* @critters-start.*?/\* @critters-end \*/', lambda m: block, t, flags=re.S)
    else:
        t = t.replace('class DashboardStudioFx extends HTMLElement {', block + '\n\nclass DashboardStudioFx extends HTMLElement {', 1)
    c.write_text(t)
print('critters synced:', len(art), 'pieces of art,', len(css), 'CSS lines')
